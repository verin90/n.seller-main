import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
import pg from 'pg';
import { fileURLToPath } from 'node:url';

export const dataDir = process.env.DATA_DIR || fileURLToPath(new URL('./data/', import.meta.url));

export async function openDatabase() {
    mkdirSync(dataDir, { recursive: true });
    const postgres = Boolean(process.env.DATABASE_URL);
    let query;
    if (postgres) {
        const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, allowExitOnIdle: true });
        query = async (sql, values = []) => (await pool.query(sql, values)).rows;
    } else {
        const database = new DatabaseSync(join(dataDir, 'marketplace.sqlite'), { timeout: 5000 });
        database.exec('PRAGMA journal_mode = WAL');
        query = async (sql, values = []) => {
            const bindings = [];
            const statement = database.prepare(sql.replace(/\$(\d+)/g, (_, index) => {
                bindings.push(values[Number(index) - 1]);
                return '?';
            }));
            return statement.columns().length ? statement.all(...bindings) : statement.run(...bindings);
        };
    }

    const id = postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
    await query(`CREATE TABLE IF NOT EXISTS registration_seller (
        id ${id}, email TEXT NOT NULL UNIQUE, password TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'seller',
        name_company TEXT, country TEXT, city TEXT, adress TEXT, pocht_index TEXT, work_number TEXT,
        web_site TEXT, initials TEXT, number TEXT
    )`);
    await query(`CREATE TABLE IF NOT EXISTS car (
        id ${id}, seller_id INTEGER REFERENCES registration_seller(id), body_type TEXT, years_car INTEGER,
        proizvoditel TEXT, distance_traveled INTEGER, name_car TEXT, seller_country TEXT,
        price NUMERIC, size_car INTEGER, img_car TEXT, seller_name TEXT
    )`);
    await query(`CREATE TABLE IF NOT EXISTS tariffs (
        id INTEGER PRIMARY KEY, plan TEXT, price TEXT, "limit" TEXT, icon_tariff TEXT, dollar TEXT, month TEXT
    )`);
    await query(`CREATE TABLE IF NOT EXISTS sales_requests (
        id ${id}, name TEXT NOT NULL, email TEXT NOT NULL, phone TEXT NOT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`);
    await query(`CREATE TABLE IF NOT EXISTS messages (
        id ${id}, car_id INTEGER NOT NULL REFERENCES car(id) ON DELETE CASCADE,
        sender_id INTEGER NOT NULL REFERENCES registration_seller(id),
        recipient_id INTEGER NOT NULL REFERENCES registration_seller(id),
        body TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`);

    for (const [table, column] of [
        ['registration_seller', 'company_description'],
        ['registration_seller', 'business_hours'],
        ['car', 'description'],
        ['car', 'photos'],
    ]) {
        if (postgres) {
            await query(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${column} TEXT`);
        } else if (!(await query(`PRAGMA table_info(${table})`)).some((field) => field.name === column)) {
            await query(`ALTER TABLE ${table} ADD COLUMN ${column} TEXT`);
        }
    }

    if (!(await query('SELECT id FROM tariffs LIMIT 1')).length) {
        const tariffs = [
            [1, 'Starter', 'Бесплатно', 'До 10 объявлений', '/circles01.svg'],
            [2, 'Premium', '999 грн / месяц', 'До 25 объявлений', '/circles02.svg'],
            [3, 'Ultimate', '1 999 грн / месяц', 'До 50 объявлений', '/circles03.svg'],
        ];
        for (const tariff of tariffs) {
            await query('INSERT INTO tariffs (id,plan,price,"limit",icon_tariff) VALUES ($1,$2,$3,$4,$5) ON CONFLICT (id) DO NOTHING', tariff);
        }
    }

    return query;
}
